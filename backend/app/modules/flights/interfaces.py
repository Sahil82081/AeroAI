"""
Flight Provider Interfaces & Domain Schemas for AeroAI.

Defines the abstract contract for real-time flight tracking and inventory lookup.
Strictly distinguishes between data provenance:
- LIVE: Verified real-time telemetry from external aviation APIs (OpenSky / Aviationstack).
- MOCK: Deterministic simulated GDS/CRS data used as fallback.
- PREDICTED: Machine learning inference generated by the AeroAI delay predictor.
"""

from abc import ABC, abstractmethod
from typing import Optional, List, Dict, Any, Literal
from datetime import datetime, timezone
from pydantic import BaseModel, Field

DataSourceType = Literal["LIVE", "MOCK", "PREDICTED"]
FlightStatusType = Literal["SCHEDULED", "AIRBORNE", "ACTIVE", "LANDED", "DELAYED", "CANCELLED", "UNKNOWN"]


class FlightPosition(BaseModel):
    """Real-time geographic and kinematic coordinates of an aircraft in flight."""

    latitude: float = Field(..., description="Latitude in decimal degrees")
    longitude: float = Field(..., description="Longitude in decimal degrees")
    altitude_ft: float = Field(..., description="Barometric or geometric altitude in feet")
    velocity_kts: float = Field(..., description="Ground speed in knots")
    heading_deg: Optional[float] = Field(None, description="True track heading in degrees (0-360)")
    vertical_rate_fpm: Optional[float] = Field(None, description="Climb or descent rate in feet per minute")
    on_ground: bool = Field(False, description="Whether aircraft transponder indicates surface status")


class FlightStatusRecord(BaseModel):
    """Normalized flight operational status and live tracking record."""

    flight_number: str = Field(..., description="Standard commercial flight identifier (e.g. AI202, 6E205, BA142)")
    callsign: Optional[str] = Field(None, description="Air Traffic Control ICAO callsign (e.g. AIC202, IGO205, BAW142)")
    carrier_code: str = Field(..., description="Two-letter IATA carrier code (e.g. AI, 6E, UK, BA, DL)")
    carrier_name: str = Field(..., description="Full airline name (e.g. Air India, IndiGo, British Airways)")
    origin: str = Field(..., description="Three-letter IATA departure airport code (e.g. BOM, DEL, JFK, LHR)")
    origin_city: Optional[str] = Field(None, description="Departure city name")
    destination: str = Field(..., description="Three-letter IATA destination airport code (e.g. DEL, BOM, SFO, CDG)")
    destination_city: Optional[str] = Field(None, description="Destination city name")
    status: str = Field(..., description="SCHEDULED, AIRBORNE, ACTIVE, LANDED, DELAYED, or CANCELLED")

    scheduled_departure: Optional[datetime] = Field(None, description="Scheduled departure time in UTC")
    actual_departure: Optional[datetime] = Field(None, description="Actual wheels-off departure time in UTC")
    scheduled_arrival: Optional[datetime] = Field(None, description="Scheduled arrival time in UTC")
    estimated_arrival: Optional[datetime] = Field(None, description="Estimated arrival time in UTC")
    delay_minutes: int = Field(0, description="Delay duration in minutes (0 if on-time or early)")

    position: Optional[FlightPosition] = Field(None, description="Live ADS-B position coordinates if airborne")

    # Strict Data Provenance (MANDATORY)
    data_source: DataSourceType = Field(..., description="LIVE, MOCK, or PREDICTED. Never label mock as live data.")
    provider_name: str = Field(..., description="Originating provider (e.g. OpenSky Network, Aviationstack, Mock GDS)")
    is_fallback: bool = Field(False, description="True if returned via fallback mechanism due to primary provider failure")
    notes: Optional[str] = Field(None, description="Operational notes or fallback reason")
    last_updated: datetime = Field(default_factory=lambda: datetime.now(timezone.utc), description="Timestamp of status update")


class FlightInventoryItem(BaseModel):
    """Standardized flight schedule and inventory availability option."""

    flight_number: str
    carrier: str
    origin: str
    destination: str
    departure_time: datetime
    arrival_time: datetime
    duration_minutes: int
    price: float
    currency: str = "INR"
    available_seats: int
    cabin_class: str = "ECONOMY"

    # Data Provenance
    data_source: DataSourceType = Field(..., description="LIVE, MOCK, or PREDICTED")
    provider_name: str
    is_fallback: bool = False


class FlightProvider(ABC):
    """Abstract interface for aviation flight tracking and schedule providers."""

    @abstractmethod
    async def get_flight_status(
        self,
        flight_number: str,
        target_date: Optional[str] = None
    ) -> Optional[FlightStatusRecord]:
        """
        Retrieves current operational status, live telemetry, and schedule for a flight.
        Returns FlightStatusRecord with clearly marked data_source, or None if not found.
        """
        pass

    @abstractmethod
    async def search_flights(
        self,
        origin: str,
        destination: str,
        earliest_time: Optional[datetime] = None,
        min_seats: int = 1
    ) -> List[FlightInventoryItem]:
        """
        Searches available flights between origin and destination with seat availability.
        """
        pass
